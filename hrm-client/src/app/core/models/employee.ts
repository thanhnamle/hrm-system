import { IsoDate, IsoDateTime, PageQuery } from './common';

export type EmployeeStatus = 'Active' | 'Terminated';

/** GET /api/employees items. */
export interface EmployeeListItem {
  id: string;
  employeeCode: string;
  fullName: string;
  email: string;
  position: string;
  departmentId: string;
  departmentName: string;
  status: EmployeeStatus;
  hireDate: IsoDate;
}

/** GET /api/employees/{id}. */
export interface EmployeeDetail {
  id: string;
  employeeCode: string;
  firstName: string;
  lastName: string;
  fullName: string;
  email: string;
  phone: string | null;
  dateOfBirth: IsoDate | null;
  hireDate: IsoDate;
  position: string;
  departmentId: string;
  departmentName: string;
  isDepartmentManager: boolean;
  status: EmployeeStatus;
  annualLeaveBalance: number;
  createdAt: IsoDateTime;
  updatedAt: IsoDateTime | null;
}

export interface EmployeeQuery extends PageQuery {
  search?: string;
  departmentId?: string;
  status?: EmployeeStatus;
}

/** POST /api/employees. The employee code is generated by the API. */
export interface CreateEmployeeRequest {
  firstName: string;
  lastName: string;
  email: string;
  position: string;
  departmentId: string;
  hireDate: IsoDate;
  phone?: string | null;
  dateOfBirth?: IsoDate | null;
}

/** PUT /api/employees/{id}. Changing departmentId transfers the employee. */
export type UpdateEmployeeRequest = Omit<CreateEmployeeRequest, 'hireDate'>;
